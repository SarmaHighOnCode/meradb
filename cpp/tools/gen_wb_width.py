#!/usr/bin/env python3
"""cpp/tools/gen_wb_width.py -- writes cpp/src/wb_width_tables.inc, the two Unicode tables behind wb::displayWidth().

usage: gen_wb_width.py PATH/TO/FTXUI/src/ftxui/screen/string.cpp [OUTPUT.inc]

The tables are the East Asian Wide / Fullwidth intervals and the zero-width marks (the Word_Break "Extend" intervals:
combining marks, variation selectors, zero width joiner ...) of Unicode 13, the data FTXUI 5.0.0 uses for terminal
cell widths. Run it once after upgrading the table source; the result is checked in, so the build never runs it.
"""
import os
import re
import sys


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    text = open(sys.argv[1], encoding="utf-8").read()
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "wb_width_tables.inc")
    full = re.search(r"g_full_width_characters = \{\{(.*?)\}\};", text, re.S).group(1)
    wide = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9a-fA-F]+), 0x([0-9a-fA-F]+)\}", full)]
    breaks = re.search(r"g_word_break_intervals = \{\{(.*?)\n\}\};", text, re.S).group(1)
    extend = [(int(a, 16), int(b, 16)) for a, b, p in re.findall(r"\{0x([0-9a-fA-F]+), 0x([0-9a-fA-F]+), WBP::(\w+)\}", breaks) if p == "Extend"]

    def table(name, rows):
        lines = ["static const CodepointInterval %s[] = {" % name]
        for i in range(0, len(rows), 3):
            lines.append("    " + " ".join("{0x%05x, 0x%05x}," % r for r in rows[i:i + 3]))
        lines.append("};")
        return "\n".join(lines)

    body = ("// GENERATED by tools/gen_wb_width.py from the Unicode 13 data in FTXUI 5.0.0's string.cpp; do not edit.\n"
            "// Sorted, non-overlapping [first, last] intervals.\n" + table("kWideIntervals", wide) + "\n\n" +
            table("kZeroWidthIntervals", extend) + "\n")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("wrote %s: %d wide, %d zero-width intervals" % (out, len(wide), len(extend)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
